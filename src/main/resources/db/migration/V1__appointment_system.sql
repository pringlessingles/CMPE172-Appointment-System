-- Run once on PostgreSQL. Never drop user data during application startup.
CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('CUSTOMER', 'PROVIDER', 'ADMIN')),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE providers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL UNIQUE REFERENCES users(id),
    specialty VARCHAR(120) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);
CREATE TABLE services (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL REFERENCES providers(id),
    name VARCHAR(120) NOT NULL,
    description VARCHAR(500) NOT NULL,
    duration_minutes INTEGER NOT NULL CHECK (duration_minutes BETWEEN 10 AND 480),
    price DECIMAL(10,2) NOT NULL CHECK (price >= 0),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    UNIQUE (provider_id, name),
    UNIQUE (id, provider_id)
);
CREATE TABLE availability_slots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider_id BIGINT NOT NULL REFERENCES providers(id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    starts_at TIMESTAMP NOT NULL,
    ends_at TIMESTAMP NOT NULL CHECK (ends_at > starts_at),
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE' CHECK (status IN ('AVAILABLE','BOOKED','BLOCKED')),
    version BIGINT NOT NULL DEFAULT 0,
    UNIQUE (id, provider_id, service_id),
    UNIQUE (provider_id, starts_at),
    FOREIGN KEY (service_id, provider_id) REFERENCES services(id, provider_id)
);
CREATE TABLE appointments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_user_id BIGINT NOT NULL REFERENCES users(id),
    provider_id BIGINT NOT NULL REFERENCES providers(id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    availability_slot_id BIGINT NOT NULL REFERENCES availability_slots(id),
    status VARCHAR(20) NOT NULL DEFAULT 'BOOKED' CHECK (status IN ('BOOKED','CANCELLED','COMPLETED')),
    booked_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    active_slot_id BIGINT GENERATED ALWAYS AS
        (CASE WHEN status = 'BOOKED' THEN availability_slot_id ELSE NULL END) STORED,
    CONSTRAINT uq_appointments_slot UNIQUE (active_slot_id),
    FOREIGN KEY (availability_slot_id, provider_id, service_id) REFERENCES availability_slots(id, provider_id, service_id)
);
CREATE INDEX idx_slots_search ON availability_slots(status, starts_at, provider_id, service_id);
CREATE INDEX idx_appointments_customer ON appointments(customer_user_id, booked_at);
CREATE INDEX idx_appointments_provider ON appointments(provider_id, booked_at);
CREATE TABLE notification_outbox (
    event_id VARCHAR(36) PRIMARY KEY,
    recipient VARCHAR(255) NOT NULL,
    type VARCHAR(40) NOT NULL,
    message VARCHAR(1000) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    next_attempt_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    attempts INTEGER NOT NULL DEFAULT 0,
    delivered_at TIMESTAMP
);
CREATE INDEX idx_outbox_pending ON notification_outbox(delivered_at, next_attempt_at);
CREATE TABLE notification_receipts (
    event_id VARCHAR(36) PRIMARY KEY,
    fingerprint VARCHAR(64) NOT NULL,
    received_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
