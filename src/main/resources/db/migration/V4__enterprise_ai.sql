CREATE TABLE ai_conversations (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ai_conversations_owner ON ai_conversations(user_id, created_at);
CREATE TABLE ai_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id VARCHAR(36) NOT NULL REFERENCES ai_conversations(id),
    role VARCHAR(12) NOT NULL CHECK (role IN ('USER', 'ASSISTANT')),
    content TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_ai_messages_conversation ON ai_messages(conversation_id, id);
CREATE TABLE ai_actions (
    id VARCHAR(36) PRIMARY KEY,
    conversation_id VARCHAR(36) NOT NULL REFERENCES ai_conversations(id),
    kind VARCHAR(10) NOT NULL CHECK (kind IN ('BOOK', 'CANCEL')),
    slot_id BIGINT NOT NULL REFERENCES availability_slots(id),
    service_id BIGINT NOT NULL REFERENCES services(id),
    appointment_id BIGINT REFERENCES appointments(id),
    slot_version BIGINT NOT NULL,
    summary VARCHAR(1000) NOT NULL,
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONFIRMED', 'DISCARDED')),
    expires_at TIMESTAMP NOT NULL
);
CREATE INDEX idx_ai_actions_conversation ON ai_actions(conversation_id, status);
CREATE TABLE ai_reminders (
    appointment_id BIGINT PRIMARY KEY REFERENCES appointments(id),
    status VARCHAR(12) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'ENQUEUED', 'SKIPPED')),
    attempts INTEGER NOT NULL DEFAULT 0,
    lease_until TIMESTAMP,
    event_id VARCHAR(36) REFERENCES notification_outbox(event_id),
    queued_at TIMESTAMP
);
